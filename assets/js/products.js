/* =======================================================
       FAKE AJAX
       ======================================================= */
function fetchProduct(id) {
  return new Promise((resolve) => {
    setTimeout(() => {
      resolve(PRODUCTS.find((p) => p.id === id) || null);
    }, 200);
  });
}

function fetchRelated(product) {
  return new Promise((resolve) => {
    setTimeout(() => {
      const related = PRODUCTS.filter(
        (p) => p.id !== product.id && p.category === product.category,
      ).slice(0, 4);
      resolve(related);
    }, 200);
  });
}

